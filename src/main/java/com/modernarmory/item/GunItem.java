package com.modernarmory.item;

import java.util.List;
import java.util.function.Consumer;

import com.modernarmory.attachment.Attachment;
import com.modernarmory.attachment.AttachmentType;
import com.modernarmory.attachment.GunAttachments;
import com.modernarmory.attachment.GunStats;
import com.modernarmory.client.renderer.GunRenderer;
import com.modernarmory.gun.FireMode;
import com.modernarmory.gun.GunDefinition;
import com.modernarmory.gun.GunSpec;
import com.modernarmory.registry.ModDataComponents;
import com.modernarmory.registry.ModItems;

import net.minecraft.ChatFormatting;
import net.minecraft.client.renderer.BlockEntityWithoutLevelRenderer;
import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.item.UseAnim;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import software.bernie.geckolib.animatable.GeoItem;
import software.bernie.geckolib.animatable.SingletonGeoAnimatable;
import software.bernie.geckolib.animatable.client.GeoRenderProvider;
import software.bernie.geckolib.animatable.instance.AnimatableInstanceCache;
import software.bernie.geckolib.animation.AnimatableManager;
import software.bernie.geckolib.util.GeckoLibUtil;

/**
 * A firearm rendered with a GeckoLib model. One class for every gun: what a gun is and does comes
 * from its {@link GunDefinition} in the {@code Guns} catalog. Its model, texture and animations are
 * found by the definition's model id: geo/item/&lt;model&gt;.geo.json, textures/item/&lt;model&gt;.png
 * and animations/item/&lt;model&gt;.animation.json (generated by tools/modelgen).
 */
public class GunItem extends Item implements GeoItem {
    private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);
    private final GunDefinition definition;
    private final GunSpec spec;

    public GunItem(GunDefinition definition, Properties properties) {
        super(properties);
        this.definition = definition;
        this.spec = definition.spec();
        SingletonGeoAnimatable.registerSyncedAnimatable(this);
    }

    public GunDefinition definition() {
        return definition;
    }

    public GunSpec spec() {
        return spec;
    }

    /** Name of the GeckoLib model/texture/animation files this gun renders with. */
    public String modelId() {
        return definition.modelId();
    }

    /** Registry path of this gun, e.g. "m4". */
    public String gunId() {
        return definition.id();
    }

    /** The ammo item this gun loads (its cartridge's ball round). */
    public Item ammoItem() {
        return ModItems.ammo(spec.cartridge());
    }

    /** Its cartridge's tracer ammo item, or null when the cartridge has no tracer. */
    public Item tracerAmmoItem() {
        return ModItems.tracerAmmo(spec.cartridge());
    }

    /** Whether this stack is ammo this gun can load (ball or tracer). */
    public boolean isAmmo(ItemStack ammo) {
        Item t = tracerAmmoItem();
        return ammo.is(ammoItem()) || (t != null && ammo.is(t));
    }

    /** The ammo item matching what is loaded now (for unloading). */
    public Item loadedAmmoItem(ItemStack stack) {
        Item t = tracerAmmoItem();
        return loadedTracer(stack) && t != null ? t : ammoItem();
    }

    /** Lang entry if there is one, else the catalog's English name. */
    @Override
    public Component getName(ItemStack stack) {
        return Component.translatableWithFallback(getDescriptionId(stack), definition.displayName());
    }

    // ---- per-stack state ----------------------------------------------

    public int ammo(ItemStack stack) {
        return stack.getOrDefault(ModDataComponents.AMMO.get(), spec.magazineSize());
    }

    public void setAmmo(ItemStack stack, int ammo) {
        stack.set(ModDataComponents.AMMO.get(), ammo);
    }

    /** True when the loaded rounds are tracers. */
    public boolean loadedTracer(ItemStack stack) {
        return stack.getOrDefault(ModDataComponents.TRACER.get(), false);
    }

    public void setLoadedTracer(ItemStack stack, boolean tracer) {
        stack.set(ModDataComponents.TRACER.get(), tracer);
    }

    /** Fitted attachments; a gun that was never customised has its factory defaults. */
    public GunAttachments attachments(ItemStack stack) {
        GunAttachments a = stack.get(ModDataComponents.ATTACHMENTS.get());
        return a != null ? a : new GunAttachments(spec.defaultAttachments());
    }

    public void setAttachments(ItemStack stack, GunAttachments attachments) {
        stack.set(ModDataComponents.ATTACHMENTS.get(), attachments);
    }

    public FireMode fireMode(ItemStack stack) {
        int i = stack.getOrDefault(ModDataComponents.FIRE_MODE.get(), spec.defaultFireModeIndex());
        return spec.fireModes().get(Math.floorMod(i, spec.fireModes().size()));
    }

    public FireMode cycleFireMode(ItemStack stack) {
        int i = stack.getOrDefault(ModDataComponents.FIRE_MODE.get(), spec.defaultFireModeIndex()) + 1;
        i = Math.floorMod(i, spec.fireModes().size());
        stack.set(ModDataComponents.FIRE_MODE.get(), i);
        return spec.fireModes().get(i);
    }

    // ---- behave like a gun, not a sword --------------------------------

    @Override
    public boolean canAttackBlock(BlockState state, Level level, BlockPos pos, Player player) {
        return false;
    }

    @Override
    public boolean onEntitySwing(ItemStack stack, LivingEntity entity, InteractionHand hand) {
        return true; // no arm swing
    }

    @Override
    public boolean shouldCauseReequipAnimation(ItemStack oldStack, ItemStack newStack, boolean slotChanged) {
        return slotChanged || oldStack.getItem() != newStack.getItem(); // ammo changes don't bob the gun
    }

    @Override
    public boolean shouldCauseBlockBreakReset(ItemStack oldStack, ItemStack newStack) {
        return false;
    }

    @Override
    public UseAnim getUseAnimation(ItemStack stack) {
        return UseAnim.NONE;
    }

    @Override
    public void appendHoverText(ItemStack stack, TooltipContext context, List<Component> tooltip, TooltipFlag flag) {
        tooltip.add(Component.literal(ammo(stack) + " / " + GunStats.of(this, stack).magazineSize() + " rounds  |  " + fireMode(stack).label())
                .withStyle(ChatFormatting.GRAY));
        tooltip.add(Component.literal(spec.cartridge().name()).withStyle(ChatFormatting.DARK_GRAY));
        GunAttachments atts = attachments(stack);
        for (AttachmentType t : AttachmentType.values()) {
            Attachment a = atts.get(t);
            if (a != null && spec.slots().contains(t))
                tooltip.add(Component.literal("+ " + a.name()).withStyle(ChatFormatting.BLUE));
        }
        tooltip.add(Component.literal(String.format("%.0f m/s  |  %.0f rpm  |  %.0f J", spec.muzzleVelocity(),
                spec.rpm(), spec.muzzleEnergy())).withStyle(ChatFormatting.DARK_GRAY));
    }

    // ---- GeckoLib --------------------------------------------------------

    @Override
    public void createGeoRenderer(Consumer<GeoRenderProvider> consumer) {
        consumer.accept(new GeoRenderProvider() {
            private GunRenderer renderer;

            @Override
            public BlockEntityWithoutLevelRenderer getGeoItemRenderer() {
                if (this.renderer == null)
                    this.renderer = new GunRenderer(GunItem.this);
                return this.renderer;
            }
        });
    }

    @Override
    public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
        GunAnimations.register(this, controllers);
    }

    @Override
    public AnimatableInstanceCache getAnimatableInstanceCache() {
        return this.cache;
    }
}
