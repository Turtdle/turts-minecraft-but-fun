"""SIG Sauer M7 (XM7, NGSW rifle) - 6.8x51 MCX-Spear, coyote, side-folding skeletal stock.

Silhouette: slab-sided upper with a continuous top rail, long M-LOK handguard that runs almost
to the muzzle, thick barrel, deep 20-round SR-25 magazine; the issued can starts right at the
handguard. 13 in barrel -> 9.5 units; bare gun 23.75 units (butt z 9, muzzle z -14.75),
28.25 with the suppressor (real: 914 mm = 27.3).

The whole rifle is generated by ngsw.SpearRifle from the spec below; the XM8 is the same class
with other numbers. Scale / axes as the M4 (see the IN-GAME TUNING NOTES in m4.py).
"""
import ngsw
from armorygen import Model

GUN = ngsw.SpearRifle(
    id="m7",
    handguard_front_z=-12.0,
    muzzle_z=-12.5,                     # suppressor mount, just in front of the handguard
    barrel_inflate=0.25,                # thick barrel
    left_hand=(0, 4, -7.5),             # under the handguard, behind the bottom rail section
    underbarrel=(0, 3.5, -10),
    side=(1.25, ngsw.BORE_Y, -10),
    stock_folding=True,
    mag_len=3.0, mag_curve=8.0, mag_material="mag_black",   # 20 rounds
    rpm=750, reload_s=2.6, empty_reload_s=3.2,
)
SIGHT_Y = GUN.sight_y                   # 8.25: axis of the issued optic (no iron sights)
EYE_Z = GUN.eye_z


def model() -> Model:
    return GUN.build()
